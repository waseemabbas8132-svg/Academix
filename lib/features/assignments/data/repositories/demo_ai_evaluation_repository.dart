class DemoAIEvaluationRepository implements AIEvaluationRepository {
  DemoAIEvaluationRepository() : _rubric = _createRubric(), _job = _createJob();

  final AssignmentRubric _rubric;
  EvaluationJob _job;
  bool _published = false;

  bool get isPublished => _published;

  @override
  Future<AssignmentRubric> getRubric(String token, String assignmentId) async =>
      _rubric;

  @override
  Future<AssignmentRubric> saveRubric(
    String token,
    String assignmentId,
    Map<String, dynamic> values,
  ) async => _rubric;

  @override
  Future<EvaluationJob?> getLatest(String token, String submissionId) async =>
      _job;

  @override
  Future<EvaluationJob> request(
    String token,
    String submissionId, {
    bool force = false,
  }) async {
    throw UnsupportedError(
      'Live AI evaluation is disabled in the demo fixture.',
    );
  }

  @override
  Future<EvaluationJob> retry(String token, String jobId) async {
    throw UnsupportedError(
      'Live AI evaluation is disabled in the demo fixture.',
    );
  }

  @override
  Future<AIEvaluation> saveReview(
    String token,
    String evaluationId, {
    required String feedback,
    required Map<String, double?> questionMarks,
    required Map<String, String> questionFeedback,
  }) async {
    final evaluation = _evaluation;
    if (questionMarks.length != evaluation.questions.length ||
        questionMarks.values.any(
          (mark) =>
              mark != null &&
              (!mark.isFinite || mark < 0 || mark > evaluation.maximumMarks),
        )) {
      throw ArgumentError(
        'Fixture marks must be finite and within the rubric.',
      );
    }
    final sum = questionMarks.values.fold<double>(
      0,
      (total, mark) => total + (mark ?? 0),
    );
    if (sum > evaluation.maximumMarks) {
      throw ArgumentError('Fixture question marks cannot exceed the rubric.');
    }
    final updatedQuestions = evaluation.questions
        .map(
          (question) => QuestionEvaluation(
            questionId: question.questionId,
            suggestedMarks: question.suggestedMarks,
            teacherMarks: questionMarks.containsKey(question.questionId)
                ? questionMarks[question.questionId]
                : question.teacherMarks,
            maximumMarks: question.maximumMarks,
            confidence: question.confidence,
            explanation: question.explanation,
            feedback: question.feedback,
            evidence: question.evidence,
            needsReview: question.needsReview,
          ),
        )
        .toList();
    final feedbackItems = [
      ...evaluation.feedbackItems,
      for (final entry in questionFeedback.entries)
        EvaluationFeedback(
          kind: 'teacher_question_feedback',
          message: entry.value,
          details: {'question_id': entry.key},
        ),
    ];
    final updated = _copyEvaluation(
      evaluation,
      questions: updatedQuestions,
      feedbackItems: feedbackItems,
      teacherFeedback: feedback,
    );
    _replaceEvaluation(updated);
    return updated;
  }

  @override
  Future<AIEvaluation> approve(
    String token,
    String evaluationId, {
    required double marks,
    required String feedback,
    required Map<String, double> questionMarks,
    required Map<String, String> questionFeedback,
  }) async {
    final evaluation = _evaluation;
    final updatedQuestions = evaluation.questions
        .map(
          (question) => QuestionEvaluation(
            questionId: question.questionId,
            suggestedMarks: question.suggestedMarks,
            teacherMarks: questionMarks[question.questionId],
            maximumMarks: question.maximumMarks,
            confidence: question.confidence,
            explanation: question.explanation,
            feedback: question.feedback,
            evidence: question.evidence,
            needsReview: question.needsReview,
          ),
        )
        .toList();
    final feedbackItems = [
      ...evaluation.feedbackItems,
      for (final entry in questionFeedback.entries)
        EvaluationFeedback(
          kind: 'teacher_question_feedback',
          message: entry.value,
          details: {'question_id': entry.key},
        ),
    ];
    final updated = _copyEvaluation(
      evaluation,
      questions: updatedQuestions,
      feedbackItems: feedbackItems,
      reviewStatus: 'approved',
      approvedMarks: marks,
      teacherFeedback: feedback,
    );
    _published = false;
    _replaceEvaluation(updated);
    return updated;
  }

  @override
  Future<void> publish(String token, String evaluationId) async {
    if (_evaluation.reviewStatus != 'approved' ||
        _evaluation.approvedMarks == null ||
        _evaluation.teacherFeedback == null) {
      throw StateError(
        'Approve the demonstration evaluation before publishing.',
      );
    }
    _published = true;
  }

  @override
  Future<bool> isGradePublished(
    String token,
    String submissionId, {
    required double approvedMarks,
    required String teacherFeedback,
  }) async =>
      _published &&
      _evaluation.approvedMarks == approvedMarks &&
      _evaluation.teacherFeedback == teacherFeedback;

  @override
  Future<AIEvaluation> reject(
    String token,
    String evaluationId,
    String reason,
  ) async {
    final updated = _copyEvaluation(
      _evaluation,
      reviewStatus: 'rejected',
      feedbackItems: [
        ..._evaluation.feedbackItems,
        EvaluationFeedback(
          kind: 'teacher_rejection',
          message: reason,
          details: const {'local_fixture_only': true},
        ),
      ],
    );
    _published = false;
    _replaceEvaluation(updated);
    return updated;
  }

  AIEvaluation get _evaluation => _job.evaluation!;

  void _replaceEvaluation(AIEvaluation evaluation) {
    _job = EvaluationJob(
      id: _job.id,
      submissionId: _job.submissionId,
      status: _job.status,
      attemptCount: _job.attemptCount,
      errorSummary: _job.errorSummary,
      extractedAnswers: _job.extractedAnswers,
      evaluation: evaluation,
    );
  }
}

