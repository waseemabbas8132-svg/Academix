AIEvaluation _copyEvaluation(
  AIEvaluation evaluation, {
  List<QuestionEvaluation>? questions,
  List<EvaluationFeedback>? feedbackItems,
  String? reviewStatus,
  double? approvedMarks,
  String? teacherFeedback,
}) => AIEvaluation(
  id: evaluation.id,
  suggestedTotal: evaluation.suggestedTotal,
  maximumMarks: evaluation.maximumMarks,
  confidence: evaluation.confidence,
  explanation: evaluation.explanation,
  feedback: evaluation.feedback,
  modelName: evaluation.modelName,
  modelVersion: evaluation.modelVersion,
  reviewStatus: reviewStatus ?? evaluation.reviewStatus,
  approvedMarks: approvedMarks ?? evaluation.approvedMarks,
  teacherFeedback: teacherFeedback ?? evaluation.teacherFeedback,
  questions: questions ?? evaluation.questions,
  feedbackItems: feedbackItems ?? evaluation.feedbackItems,
);
